/**
 * Скролл-цепочка Hero → Intro → Location1 → Cliff → Qualities → Above →
 * Capacity → Presence.
 *
 * Каждая секция в цепочке — `position: sticky; top: 0` внутри собственной
 * `<Имя>-pin-wrap` обёртки (высота задаётся статическим CSS — либо
 * литеральным `vh` при рендере, либо, у горизонтальных галерей
 * Location2Section.tsx/ResidenceSection.tsx, императивно из реальной
 * ширины трека). Секции, которые должны «наехать» поверх предыдущей и
 * полностью закрыть её (настоящий cover-переход, а не последовательная
 * прокрутка, где обе секции едут одновременно и видны разом,
 * разрезанные пополам), сдвинуты статическим (заданным один раз при
 * рендере, не пересчитываемым в JS на каждый тик скролла) `margin-top:
 * -100vh` на своей wrap-обёртке — этот отрицательный margin утягивает
 * документный верх текущей обёртки ровно на 1 вьюпорт раньше, чем
 * закончилась бы предыдущая "по прямому потоку", то есть ровно туда, где
 * предыдущая секция замирает (уже полностью раскрытой) на свой лишний
 * "freeze"-вьюпорт. Никакого JS для самого наезда — весь эффект даёт
 * разница между высотой предыдущей обёртки и margin-top на текущей (см.
 * HeroSection.tsx/IntroSection.tsx как эталон, дальше по цепочке —
 * Location1Section.tsx/CliffSection.tsx/AboveSection.tsx/
 * CapacitySection.tsx/PresenceSection.tsx).
 *
 * Раньше (до 2026-09-08) секции глубже Intro держались на GSAP
 * `pin: true` вместо sticky — это открыло целый класс багов: `pin: true`
 * в паре с отрицательным margin на запиненном элементе ненадёжно
 * переносит margin на свой pin-spacer (GSAP сам предупреждает об этом
 * в документации), а в связке с React StrictMode (двойной
 * mount/cleanup/mount эффекта в dev, см. `npm run dev`) секция могла
 * целиком проваливаться на 1 вьюпорт ниже видимой области на весь пин —
 * баг не проявлялся в проде (`npm run build`), только в dev, что делало
 * его особенно коварным при разработке. `position: sticky` не создаёт
 * pin-спейсеров и ничего не пересчитывает — обёртка вокруг секции
 * физически резервирует нужную высоту в потоке документа, полностью
 * своя для браузера, без прослойки GSAP.
 *
 * Абсолютные формулы-функции (`heroPinEnd`/`introPinEnd`/…), которыми
 * этот файл когда-то делился с секциями глубже Intro, здесь больше не
 * нужны: каждая секция меряет начало своей собственной обёртки живьём
 * через `getBoundingClientRect()` (см. `wrapTop()` в каждом файле) — это
 * не может "устареть" или разойтись с реальной вёрсткой, в отличие от
 * готовой формулы. Здесь остаются только константы длительности
 * собственной (reveal) фазы Hero/Intro — на них всё ещё замкнута их пара
 * ScrollTrigger'ов (без pin, см. комментарии в этих файлах).
 */

